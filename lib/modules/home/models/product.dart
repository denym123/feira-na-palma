class Product {
  final String? id;
  final String? name;
  final String? image;
  final String? price;
  final String? unit;
  final String? producerName;

  Product({
    required this.id,
    required this.name,
    required this.image,
    required this.price,
    required this.unit,
    required this.producerName,
  });
}
